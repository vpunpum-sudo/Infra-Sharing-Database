import type { Point, Rect } from './wiScreenshotPoint';
import { WI_FIGURE_IDS, type FigureId } from './wiScreenshotFigures';

export type Mark = Point;
/** Where the marker sits on the measured box: its centre, its top-left corner, or the middle of its left edge. */
export type MarkAnchor = 'center' | 'top-left' | 'left-center';
export type MarkBox = { name: string; box?: Rect; anchor?: MarkAnchor };
const round = (value: number) => Math.round(value * 10) / 10;

export function clampMark(mark: Mark): Mark {
  return { x: Math.max(0, Math.min(100, round(mark.x))), y: Math.max(0, Math.min(100, round(mark.y))) };
}

export function toPercentMarks(boxes: MarkBox[], clip: { x?: number; y?: number; width: number; height: number }, previous: Mark[] = []): {
  marks: Mark[]; measured: string[]; kept: string[]; warnings: string[];
} {
  const measured: string[] = [];
  const kept: string[] = [];
  const warnings: string[] = [];
  const marks = boxes.map((item, index) => {
    if (!item.box || item.box.width <= 0 || item.box.height <= 0) {
      kept.push(item.name);
      return clampMark(previous[index] ?? { x: 50, y: 50 });
    }
    measured.push(item.name);
    const anchor = item.anchor ?? 'center';
    const x = anchor === 'center' ? item.box.x + item.box.width / 2 : item.box.x;
    const y = anchor === 'top-left' ? item.box.y : item.box.y + item.box.height / 2;
    const raw = { x: ((x - (clip.x ?? 0)) / clip.width) * 100, y: ((y - (clip.y ?? 0)) / clip.height) * 100 };
    if (raw.x < 0 || raw.x > 100 || raw.y < 0 || raw.y > 100) warnings.push(`${item.name}: mark clamped to clip`);
    return clampMark(raw);
  });
  return { marks, measured, kept, warnings };
}

export function stackParts(parts: { width: number; height: number; marks: Mark[] }[]): { width: number; height: number; marks: Mark[] } {
  const width = Math.max(...parts.map(part => part.width));
  const height = parts.reduce((sum, part) => sum + part.height, 0);
  let top = 0;
  const marks = parts.flatMap(part => {
    const converted = part.marks.map(mark => clampMark({ x: mark.x * part.width / width, y: (top + mark.y * part.height / 100) / height * 100 }));
    top += part.height;
    return converted;
  });
  return { width, height, marks };
}

export function mergeCapturedMarks<T extends string>(old: Partial<Record<T, Mark[]>>, captured: Partial<Record<T, Mark[]>>): Partial<Record<T, Mark[]>> {
  return { ...old, ...captured };
}

export function formatMarksModule(groups: Partial<Record<FigureId, Mark[]>>): string {
  const line = (mark: Mark) => {
    const bounded = clampMark(mark);
    return `    { x: ${bounded.x.toFixed(1)}, y: ${bounded.y.toFixed(1)} }`;
  };
  const entries = WI_FIGURE_IDS.filter(id => groups[id]).map(id =>
    `  ${/^[a-z]+$/.test(id) ? id : `'${id}'`}: [\n${groups[id]!.map(line).join(',\n')}\n  ]`);
  return `// Generated by npm run wi:screenshots. Review the PNGs before committing.\n` +
    `import type { FigureId } from '../utils/wiScreenshotFigures';\n` +
    `import type { Mark } from '../utils/wiScreenshotMarks';\n\n` +
    `export const WI_SCREENSHOT_MARKS: Partial<Record<FigureId, Mark[]>> = {\n${entries.join(',\n')}\n};\n`;
}
